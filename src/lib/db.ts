// Postgres: the Qloo cache, finished plans and what's made from them (city guides, decks), the public limits, and
// what each browser keeps (its tours, where their venues and sponsors stand, what's remembered about each act). The
// tables are made on first use when they're missing. Queries use ? placeholders.
import pg from "pg";
import { setting } from "./settings";

// Counts and sums come back as numbers, not strings.
pg.types.setTypeParser(20, (v) => Number(v));
pg.types.setTypeParser(1700, (v) => Number(v));

const TABLES = [
  `CREATE TABLE IF NOT EXISTS qloo_cache (key TEXT PRIMARY KEY, value TEXT NOT NULL, expires_at TEXT NOT NULL)`,
  `CREATE TABLE IF NOT EXISTS tour_plans (
     id TEXT PRIMARY KEY, act_id TEXT NOT NULL, act_name TEXT NOT NULL, plan TEXT NOT NULL,
     example INTEGER NOT NULL DEFAULT 0, parent_id TEXT, created_at TEXT NOT NULL
   )`,
  `CREATE INDEX IF NOT EXISTS tour_plans_examples ON tour_plans(example, created_at DESC)`,
  `CREATE TABLE IF NOT EXISTS tour_usage (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, visitor TEXT NOT NULL, created_at TEXT NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS tour_usage_recent ON tour_usage(created_at)`,
  `CREATE TABLE IF NOT EXISTS tour_chat_usage (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, visitor TEXT NOT NULL, created_at TEXT NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS tour_chat_usage_recent ON tour_chat_usage(created_at)`,
  `CREATE TABLE IF NOT EXISTS tour_city_guides (
     plan_id TEXT NOT NULL REFERENCES tour_plans(id) ON DELETE CASCADE, city_id TEXT NOT NULL,
     guide TEXT NOT NULL, created_at TEXT NOT NULL, PRIMARY KEY (plan_id, city_id)
   )`,
  `CREATE TABLE IF NOT EXISTS tour_decks (plan_id TEXT PRIMARY KEY REFERENCES tour_plans(id) ON DELETE CASCADE, pdf BYTEA NOT NULL, created_at TEXT NOT NULL)`,
  // `kind` is always 'plan' now; databases made before still have rows of other kinds, which are left out.
  `CREATE TABLE IF NOT EXISTS tour_saved (
     visitor TEXT NOT NULL, item_id TEXT NOT NULL, kind TEXT NOT NULL DEFAULT 'plan',
     saved_at TEXT NOT NULL, PRIMARY KEY (visitor, item_id)
   )`,
  `CREATE TABLE IF NOT EXISTS tour_statuses (
     visitor TEXT NOT NULL, tour_id TEXT NOT NULL, kind TEXT NOT NULL CHECK (kind IN ('venue','sponsor')), item_id TEXT NOT NULL,
     city_id TEXT, status TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL, PRIMARY KEY (visitor, tour_id, kind, item_id)
   )`,
  `CREATE TABLE IF NOT EXISTS tour_acts (
     visitor TEXT NOT NULL, act_id TEXT NOT NULL, act TEXT NOT NULL, prefs TEXT NOT NULL, updated_at TEXT NOT NULL, PRIMARY KEY (visitor, act_id)
   )`,
  `CREATE TABLE IF NOT EXISTS tour_profiles (visitor TEXT PRIMARY KEY, profile TEXT NOT NULL, updated_at TEXT NOT NULL)`,
];
const NAMES = TABLES.flatMap((sql) => sql.match(/^CREATE TABLE IF NOT EXISTS (\w+)/)?.[1] ?? []);

type Params = unknown[];

export interface Statement {
  get<T = Record<string, unknown>>(...params: Params): Promise<T | undefined>;
  all<T = Record<string, unknown>>(...params: Params): Promise<T[]>;
  /** For INSERT, UPDATE and DELETE: how many rows it changed. */
  run(...params: Params): Promise<{ changes: number }>;
}

export interface Database {
  prepare(sql: string): Statement;
}

/** ? placeholders numbered the way Postgres wants them ($1, $2…); quoted text is left alone. */
const numbered = (sql: string) => {
  let n = 0;
  return sql.replace(/'[^']*'|"[^"]*"|\?/g, (m) => (m === "?" ? `$${++n}` : m));
};

/**
 * Makes the tables that are missing, one server at a time. The lock ends with the transaction, because a connection
 * pooler in transaction mode (Neon's, on Vercel) can't keep a lock held across statements for a session.
 */
async function makeTables(pool: pg.Pool) {
  const have = await pool.query<{ n: number }>("SELECT COUNT(*) AS n FROM pg_tables WHERE schemaname = current_schema() AND tablename = ANY($1)", [NAMES]);
  if (have.rows[0].n === NAMES.length) return;
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SELECT pg_advisory_xact_lock(7253110)");
    for (const sql of TABLES) await client.query(sql);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK").catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}

// One pool per server process, kept across reloads in development.
const state = globalThis as unknown as { __database?: { pool: pg.Pool; ready: Promise<void> } };

function connection() {
  if (!state.__database) {
    const url = setting("DATABASE_URL");
    if (!url) throw new Error("DATABASE_URL isn't set: add a Postgres address to .env.local.");
    const pool = new pg.Pool({ connectionString: url, max: 5 });
    // A dropped connection is replaced on the next query; it mustn't stop the server.
    pool.on("error", () => {});
    const ready = makeTables(pool);
    const current = { pool, ready };
    // If the tables couldn't be checked, the next query tries again.
    ready.catch(() => {
      if (state.__database === current) state.__database = undefined;
      void pool.end().catch(() => {});
    });
    state.__database = current;
  }
  return state.__database;
}

const statement = (query: (sql: string, params: Params) => Promise<pg.QueryResult>, sql: string): Statement => ({
  get: async <T,>(...params: Params) => (await query(numbered(sql), params)).rows[0] as T | undefined,
  all: async <T,>(...params: Params) => (await query(numbered(sql), params)).rows as T[],
  run: async (...params: Params) => ({ changes: (await query(numbered(sql), params)).rowCount ?? 0 }),
});

export function db(): Database {
  const query = async (sql: string, params: Params) => {
    const { pool, ready } = connection();
    await ready;
    return pool.query(sql, params);
  };
  return { prepare: (sql) => statement(query, sql) };
}

/** Runs `work` in one transaction: all of it, or none. */
export async function transaction<T>(work: (database: Database) => Promise<T>): Promise<T> {
  const { pool, ready } = connection();
  await ready;
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const result = await work({ prepare: (sql) => statement((text, params) => client.query(text, params), sql) });
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK").catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}

/** The time now, as stored: an ISO string. */
export const now = () => new Date().toISOString();

/** Closes the pool, for scripts and tests that end. */
export async function closeDb() {
  const current = state.__database;
  state.__database = undefined;
  await current?.pool.end();
}
